const path = require('path');
const fs = require('fs');

const { withAndroidManifest, withDangerousMod } = require('expo/config-plugins');

/** From API 31, `allowBackup` covers cloud backup only; device transfer needs the XML rules. */
module.exports = function withChiavoraBackup(config) {
  // Read from the resolved config, so it does not depend on the order of manifest mods.
  if (config.android?.allowBackup !== false) {
    throw new Error(
      'with-chiavora-backup: app.json must set expo.android.allowBackup to false. ' +
        'allowBackup governs cloud backup and the XML rules govern device transfer; ' +
        'the vault needs both.',
    );
  }
  return withRuleFiles(withManifestAttributes(config));
};

function withManifestAttributes(config) {
  return withAndroidManifest(config, (modConfig) => {
    const application = modConfig.modResults.manifest.application?.[0];
    if (!application) {
      throw new Error('with-chiavora-backup: the generated manifest has no <application>');
    }
    application.$['android:dataExtractionRules'] = '@xml/chiavora_data_extraction_rules';
    application.$['android:fullBackupContent'] = '@xml/chiavora_backup_rules';
    return modConfig;
  });
}

const DOMAINS = [
  'root',
  'file',
  'database',
  'sharedpref',
  'external',
  'device_root',
  'device_file',
  'device_database',
  'device_sharedpref',
];

function withRuleFiles(config) {
  return withDangerousMod(config, [
    'android',
    async (modConfig) => {
      const xmlDir = path.join(
        modConfig.modRequest.platformProjectRoot,
        'app',
        'src',
        'main',
        'res',
        'xml',
      );
      await fs.promises.mkdir(xmlDir, { recursive: true });

      const excludes = (indent) =>
        DOMAINS.map((domain) => `${indent}<exclude domain="${domain}" />`).join('\n');

      await fs.promises.writeFile(
        path.join(xmlDir, 'chiavora_data_extraction_rules.xml'),
        [
          '<?xml version="1.0" encoding="utf-8"?>',
          '<!-- Generated by apps/mobile/plugins/with-chiavora-backup.js.',
          '     Edit the plugin; this file is regenerated by prebuild. -->',
          '<data-extraction-rules>',
          '    <cloud-backup>',
          excludes('        '),
          '    </cloud-backup>',
          '    <device-transfer>',
          excludes('        '),
          '    </device-transfer>',
          '</data-extraction-rules>',
          '',
        ].join('\n'),
        'utf8',
      );

      // API 26–30, in case `allowBackup` is ever flipped. Every exclude needs a `path`; `.` is
      // the whole domain.
      await fs.promises.writeFile(
        path.join(xmlDir, 'chiavora_backup_rules.xml'),
        [
          '<?xml version="1.0" encoding="utf-8"?>',
          '<!-- Generated by apps/mobile/plugins/with-chiavora-backup.js.',
          '     API 26-30 only. -->',
          '<full-backup-content>',
          ...['root', 'file', 'database', 'sharedpref'].map(
            (domain) => `    <exclude domain="${domain}" path="." />`,
          ),
          '</full-backup-content>',
          '',
        ].join('\n'),
        'utf8',
      );

      return modConfig;
    },
  ]);
}
